import type {
  DiagnosticSeverity,
  DoctorRuleDefinition,
  SourceBlockKind
} from '@vue-doctor/core'

interface ParseFailureOrder {
  template?: number
  script?: number
}

interface VueRuleRecord extends Omit<
  DoctorRuleDefinition,
  'description' | 'verification' | 'requires' | 'help'
> {
  problem: string
  remediation: string
  sourceBlocks?: SourceBlockKind[]
  allSourceBlocks?: SourceBlockKind[]
  vueVersion?: 'known'
  parseFailureOrder?: ParseFailureOrder
  contextualSeverity?: boolean
}

interface InternalVueRuleDefinition extends DoctorRuleDefinition {
  parseFailureOrder?: ParseFailureOrder
  contextualSeverity?: boolean
}

function defineVueRule(record: VueRuleRecord): InternalVueRuleDefinition {
  const {
    problem,
    remediation,
    sourceBlocks: declaredSourceBlocks,
    allSourceBlocks,
    vueVersion,
    parseFailureOrder,
    ...definition
  } = record
  const sourceBlocks: SourceBlockKind[] = declaredSourceBlocks ? [...declaredSourceBlocks] : []
  if (!declaredSourceBlocks) {
    if (parseFailureOrder?.template !== undefined) sourceBlocks.push('template')
    if (parseFailureOrder?.script !== undefined) sourceBlocks.push('script', 'script-setup')
  }

  return {
    ...definition,
    domain: record.domain ?? 'vue',
    tags: record.tags ?? vueRuleTags(record.code),
    description: problem,
    verification: 'static',
    requires: {
      sourceBlocks: [...new Set(sourceBlocks)],
      ...(allSourceBlocks ? { allSourceBlocks: [...new Set(allSourceBlocks)] } : {}),
      ...(vueVersion ? { vueVersion } : {})
    },
    help: { problem, remediation },
    ...(parseFailureOrder ? { parseFailureOrder } : {})
  }
}

function vueRuleTags(code: string): string[] {
  const tags = ['vue']
  if (/watch|ref|reactive|computed|props-destructure/.test(code)) tags.push('reactivity')
  if (/watch/.test(code)) tags.push('watcher')
  if (/template|v-for|v-if|v-html/.test(code)) tags.push('template')
  if (/emit|model|event/.test(code)) tags.push('interaction')
  if (/app-|global|plugin|provide|inject/.test(code)) tags.push('application')
  if (/prefer-/.test(code)) tags.push('suggestion')
  if (code.startsWith('vue2-')) tags.push('vue2')
  return tags
}

