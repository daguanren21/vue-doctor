const rulesByCode = new Map(internalVueRuleDefinitions.map((rule) => [rule.code, rule]))

export const vueRuleDefinitions: readonly DoctorRuleDefinition[] = internalVueRuleDefinitions

export function getVueRuleDefinition(code: string): DoctorRuleDefinition | undefined {
  return rulesByCode.get(code)
}

export function resolveVueRuleSeverity(
  code: string,
  contextualSeverity?: DiagnosticSeverity
): DiagnosticSeverity {
  const rule = rulesByCode.get(code)
  const severity = rule?.contextualSeverity && contextualSeverity
    ? contextualSeverity
    : rule?.defaultSeverity
  if (!severity) throw new Error('Vue diagnostic ' + code + ' is not declared in the rule catalog.')
  return severity
}

export function getVueRulesForFailedSourceBlock(kind: SourceBlockKind): readonly DoctorRuleDefinition[] {
  const key = kind === 'template' ? 'template' : 'script'
  return internalVueRuleDefinitions
    .filter((rule) => rule.parseFailureOrder?.[key] !== undefined)
    .sort((left, right) => left.parseFailureOrder![key]! - right.parseFailureOrder![key]!)
}
